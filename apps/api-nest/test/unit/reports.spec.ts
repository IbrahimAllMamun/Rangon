describe('a report as CSV', () => {
  it.each<[string[], string]>([
    [['a', 'b'], 'a,b\r\n'],
    [['x,y', 'he said "hi"'], '"x,y","he said ""hi"""\r\n'],
    [['line\nbreak', 'cr\rhere'], '"line\nbreak","cr\rhere"\r\n'],
    [[''], '""\r\n'],
    [['', ''], ',\r\n'],
    [[' lead', 'trail '], ' lead,trail \r\n'],
    [['Expense — Rent', '-45000.00'], 'Expense — Rent,-45000.00\r\n'],
    [['ক', ''], 'ক,\r\n'],
    [['a;b', "'q'"], "a;b,'q'\r\n"],
    [['"', ','], '"""",","\r\n'],
  ])('writes %j as %j', (row, text) => {
    expect(csvRow(row)).toBe(text);
  });

  it('writes a header and each row under it, a missing cell empty', () => {
    expect(
      csvDictWriter(['line', 'amount'], [{ line: 'a,b', amount: '1.00' }, { line: 'c' }]),
    ).toBe('line,amount\r\n"a,b",1.00\r\nc,\r\n');
  });

  it('writes a cell as str() does, and JSON as the encoder does', () => {
    const placed = new Moment('2026-10-07 11:05:00+00');
    const precise = new Moment('2026-10-07 00:09:45.750069+00');
    expect(csvCell(placed)).toBe('2026-10-07 11:05:00+00:00');
    expect(csvCell(precise)).toBe('2026-10-07 00:09:45.750069+00:00');
    expect(csvCell(new Dcm('-0.00'))).toBe('-0.00');
    expect(csvCell(null)).toBe('');
    expect(csvCell(7)).toBe('7');
    expect(
      JSON.stringify(toJson({ at: placed, total: new Dcm('8230.00'), n: 3, none: null })),
    ).toBe('{"at":"2026-10-07T11:05:00Z","total":"8230.00","n":3,"none":null}');
    // A bare Decimal through DRF's encoder: float(value), as Python writes a float.
    expect(
      JSON.stringify(toJson([{ total: new Dcm('8230.00') }, { total: new Dcm('0.10') }], true)),
    ).toBe('[{"total":8230.0},{"total":0.1}]');
  });

  it('a renderer that renders nothing leaves the keys of what it was given', () => {
    expect(CSV_RENDERER).toEqual({ format: 'csv', mediaType: 'text/csv' });
    expect(csvFallback({ error: { code: 'X' } })).toBe('error');
    expect(csvFallback({ range: {}, kpis: {}, sales_over_time: [] })).toBe(
      'rangekpissales_over_time',
    );
    expect(csvFallback({})).toBe('');
  });
});
