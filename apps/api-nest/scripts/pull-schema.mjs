// Copy the schema migrations are written against (drizzle/schema.ts, which
// keeps everything) into src/database/, minus the foreign-key constraint
// blocks. Run after editing drizzle/schema.ts or drizzle/relations.ts, beside
// `drizzle-kit generate` (docs/database/migrations.md).
//
// Those blocks are for migrations, and drizzle/schema.ts is what migrations
// are written against. In the API's copy they make the tables reference each
// other in cycles (branch -> organization -> user -> branch) that TypeScript
// cannot type, and relations.ts already carries every join the ORM needs.
// drizzle/schema.ts is not compiled: drizzle-kit loads it as it is.
import { readFileSync, writeFileSync } from 'node:fs';

const header = `// GENERATED by \`npm run db:copy\` from drizzle/schema.ts and drizzle/relations.ts.
// Do not edit: change those, generate a migration, and copy again.
`;

const schema = readFileSync('drizzle/schema.ts', 'utf8')
  .replace(/\n\tforeignKey\(\{[\s\S]*?\n\t\t\}\),/g, '')
  .replace(/\bforeignKey, /, '');
if (/foreignKey\(/.test(schema)) throw new Error('A foreignKey block survived; the generator format changed.');
writeFileSync('src/database/schema.ts', header + schema);
writeFileSync('src/database/relations.ts', header + readFileSync('drizzle/relations.ts', 'utf8'));
console.log('src/database/schema.ts and relations.ts updated.');
