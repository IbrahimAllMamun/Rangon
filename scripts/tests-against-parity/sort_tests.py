"""Sort Django's tests by what they reach that no parity case does.

    python sort_tests.py BEFORE.json AFTER.json OUT.md OUT.tsv

BEFORE and AFTER are covdiff.py's reports: the comparison as it stood, and with
the cases added since.  classes.py says what each function in them is.
"""

import collections
import json
import sys

import classes

before, after = (json.load(open(path)) for path in sys.argv[1:3])
out_md, out_tsv = sys.argv[3:5]

DJANGO_ONLY_FILES = {
    "tests/test_label_print_migration.py": "the label-mark migration",
    "tests/test_permission_sync.py": "`migrate` keeping the roles in step",
    "tests/test_seed_demo_guard.py": "the seed's guard",
    "tests/test_seed_reset.py": "the seed's reset",
    "tests/test_performance.py": "query budgets counted in ORM queries",
    "tests/unit/test_psycopg_adapters.py": "the psycopg adapter",
    "tests/unit/test_email_timeout.py": "Django's mail backend",
}
ORDER = ["to-port", "case-added", "second-door", "race", "setting", "no-caller", "django-only"]
rule = {k: v for k, v in before["regions"].items() if v["kind"] == "rule"}
still = {k for k, v in after["regions"].items() if v["kind"] == "rule"}
unknown = sorted(set(rule) - set(classes.REGIONS))
if unknown:
    sys.exit(f"not classified: {unknown}")


def sort_of(test, report):
    """(sort, why) for one test, from the functions it alone reaches while it runs."""
    path = test.split("::")[0]
    if path in DJANGO_ONLY_FILES:
        return "django-only", DJANGO_ONLY_FILES[path]
    kinds = collections.defaultdict(list)
    for region in report["tests"][test]["alone"]:
        if region in classes.REGIONS:
            kinds[classes.REGIONS[region][0]].append(region)
    for kind in ORDER:
        if kind in kinds:
            return kind, "; ".join(sorted(kinds[kind])[:3])
    return "covered", ""


rows = [(test, *sort_of(test, before)) for test in sorted(before["tests"])]
counts = collections.Counter(sort for _, sort, _ in rows)
by_file = collections.defaultdict(collections.Counter)
for test, sort, _ in rows:
    by_file[test.split("::")[0]][sort] += 1

with open(out_tsv, "w") as handle:
    handle.write("test\tsort\twhat it alone reaches\n")
    for test, sort, why in rows:
        handle.write(f"{test}\t{sort}\t{why}\n")

b, a = before["totals"], after["totals"]
lines = []
emit = lines.append
emit("<!-- GENERATED by scripts/tests-against-parity/sort_tests.py. Edit classes.py, not this. -->")
emit("")
emit("| | Before | With the cases added |")
emit("|---|---|---|")
for label, key in [
    ("Statements of rule code", "rule: statements"),
    ("reached by Django's tests", "rule: reached by the tests"),
    ("reached by the comparison", "rule: reached by the comparison"),
    ("reached by both", "rule: reached by both"),
    ("**statements only the tests reach**", "rule: statements only the tests reach"),
    ("**branches only the tests take**", "rule: branches only the tests take"),
]:
    emit(f"| {label} | {b.get(key, 0):,} | {a.get(key, 0):,} |")
emit(f"| functions holding such code | {len(rule)} | {len(still)} |")
emit("")
emit("### The tests")
emit("")
emit("| Sort | Tests | What it means |")
emit("|---|---|---|")
MEANS = {"covered": "Every statement and branch it runs is one a parity case runs too", **classes.KINDS}
MEANS["django-only"] = "A file that tests Django's own machinery, or a test reaching only that"
for sort in ["covered", *ORDER]:
    emit(f"| `{sort}` | {counts.get(sort, 0):,} | {MEANS[sort]} |")
emit(f"| | **{len(rows):,}** | |")
emit("")
emit("### The functions")
emit("")
for kind in ORDER:
    members = sorted(k for k in rule if classes.REGIONS[k][0] == kind)
    emit(f"**{classes.KINDS[kind]}** ({len(members)})")
    emit("")
    emit("| Function | Statements, branches | Tests | Note |")
    emit("|---|---|---|---|")
    for key in members:
        region = rule[key]
        note = classes.REGIONS[key][1]
        if kind == "case-added" and key in still:
            left = after["regions"][key]
            note += f" -- **still open**: {len(left['lines'])} statements, {len(left['branches'])} branches"
        emit(
            f"| `{key}` | {len(region['lines'])}, {len(region['branches'])} | "
            f"{len(region['tests'])} | {note} |"
        )
    emit("")
emit("### By file")
emit("")
emit("| File | Tests | covered | " + " | ".join(ORDER) + " |")
emit("|---|---|---|" + "---|" * len(ORDER))
for path in sorted(by_file):
    c = by_file[path]
    emit(
        f"| `{path}` | {sum(c.values())} | {c.get('covered', 0)} | "
        + " | ".join(str(c.get(kind, 0) or "") for kind in ORDER)
        + " |"
    )
open(out_md, "w").write("\n".join(lines) + "\n")
print(dict(counts), len(rule), "->", len(still))
